function isEvenOrOdd(a){
    if( a % 2 == 0){
        console.log("This number is Even");
    }
    else{
        console.log("This number is Odd");
    }
}

const isEvenOrOddArrow = (a) => {
    if (a % 2 == 0) {
        console.log("This number is Even");
    } else {
        console.log("This number is Odd");
    }
};


isEvenOrOdd(4);        
isEvenOrOddArrow(4);   

isEvenOrOdd(7);        
isEvenOrOddArrow(7); 